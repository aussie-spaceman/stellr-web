// The route manifest (S2, multi-tenant plan): every route handler, every
// metadata route and every page under app/, each in one access class. test/route-manifest.test.ts
// fails when a file is missing from this list, when an entry names a file that
// no longer exists, and when a handler does not call the guard its class needs.
// How to classify a new route: docs/SECURITY-route-manifest.md.
//
// The classes:
//   platform_admin  Stellr platform staff acting across tenants. Must reach
//                   lib/authz's platform check; a legacy admin guard does not count.
//   tenant_staff    A tenant's own staff, inside their tenant. Must reach lib/authz's
//                   tenant-membership check; a legacy admin guard does not count.
//   participant     A signed-in member acting on their own records. Session guard.
//   public          Anyone, no session needed (a capability token in the URL or
//                   a cookie still counts as public). API handlers must be
//                   rate-limited or carry an allow-listed reason.
//   webhook         A third party calling in. Must verify a signature or secret.
//   cron            Vercel Cron. guardCron must be the first statement.
//   stellr_only     Stellr's own admin portal and the admin APIs behind it,
//                   which read and write Stellr data by global id. Admin guard.
//   platform_destined  A platform function by nature, waiting on the owner's choice
//                   between platform_admin (owner-only once AUTHZ_SOURCE=postgres) and
//                   staying with Stellr staff. Admin guard, the same one as stellr_only:
//                   moving a route here moves nobody's access (C15).
//
// The rule for today's admin surface (decided in S2): every /admin page and
// every /api/admin route is stellr_only, because none of them is tenant-scoped
// yet. S5 moves each one, as it is converted to loadScoped/tenantDb, to
// tenant_staff (it acts inside one tenant) or platform_admin (it acts across
// tenants, such as staff roles or impersonation). C16 moved the first ones to
// tenant_staff. The one /api/admin route Sanity calls with a shared
// secret, not an admin session, is a webhook.
//
// Why platform_destined is not platform_admin: that class's check answers from the
// platform_admins table alone under postgres, so putting a route there decides who
// loses it at the flip. lib/security/stellr-only-dispositions.ts lists these routes,
// and the owner's choice for each is what moves it on.
//
// Keep the entries sorted within each section; the test does not depend on it.

