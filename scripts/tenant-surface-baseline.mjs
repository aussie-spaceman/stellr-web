// The baseline test/tenant-surface.test.ts compares with: what a tenant host can
// still reach of Stellr's social features. It only shrinks.
//
//   npx tsx scripts/tenant-surface-baseline.mjs           show what is measured, and the diff
//   npx tsx scripts/tenant-surface-baseline.mjs --write   shrink the baseline to what is measured
//
// --write refuses when the tree reaches something the baseline doesn't list. That is
// a finding: send the call through lib/community/event-hooks, or stop importing it.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { BASELINE_FILE, measureRepo, surfaceDiff } from '../test/tenant-surface-measure'

const measured = measureRepo()
const surface = { modules: measured.modules, edges: measured.edges, tableFiles: measured.tableFiles, channelFiles: measured.channelFiles }
const baseline = existsSync(BASELINE_FILE) ? JSON.parse(readFileSync(BASELINE_FILE, 'utf8')) : null
const { added, stale } = baseline ? surfaceDiff(baseline, surface) : { added: [], stale: [] }

console.log(`modules ${surface.modules.length}, edges ${surface.edges.length}, table files ${surface.tableFiles.length}, channel files ${surface.channelFiles.length}`)
for (const line of added) console.log(`NEW    ${line}`)
for (const line of stale) console.log(`STALE  ${line}`)

if (process.argv.includes('--write')) {
  if (added.length) {
    console.error('Refusing to write: the baseline only shrinks.')
    process.exit(1)
  }
  writeFileSync(BASELINE_FILE, `${JSON.stringify({
    $comment: 'Generated by scripts/tenant-surface-baseline.mjs. What a tenant host can still reach of the social features. Only shrinks.',
    ...surface,
  }, null, 2)}\n`)
  console.log(`Wrote ${BASELINE_FILE}`)
}
